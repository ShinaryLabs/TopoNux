IPTABLES_SAMPLE = """# Generated by iptables-save
*filter
:INPUT ACCEPT [10:800]
:FORWARD DROP [0:0]
:DOCKER - [0:0]
-A FORWARD -j DOCKER
-A DOCKER ! -i br-0123456789ab -o br-0123456789ab -j DROP
-A DOCKER -d 172.20.0.2/32 ! -i br-abc -o br-abc -p tcp -m tcp --dport 80 -m comment --comment "web" -j ACCEPT
COMMIT
*nat
:PREROUTING ACCEPT [0:0]
:DOCKER - [0:0]
-A PREROUTING -m addrtype --dst-type LOCAL -j DOCKER
-A DOCKER -i docker0 -j RETURN
-A DOCKER ! -i br-ba9876543210 -p tcp -m tcp --dport 80 -j DNAT --to-destination 172.20.0.2:80
COMMIT
"""


def test_nftables_rules_are_normalized():
    result = normalize_firewall({"backend": "nftables", "rules": NFT_SAMPLE})

    assert result["available"] is True
    assert result["backend"] == "nftables"
    assert [table["name"] for table in result["tables"]] == ["filter", "nat"]

    filter_table = result["tables"][0]
    forward = next(chain for chain in filter_table["chains"] if chain["name"] == "FORWARD")
    assert forward["hook"] == "forward"
    assert forward["policy"] == "drop"

    jump = forward["rules"][0]
    assert jump["verdict"] == "jump"
    assert jump["target"] == "DOCKER"
    assert jump["counter"] == {"packets": 68, "bytes": 27286}

    docker = next(chain for chain in filter_table["chains"] if chain["name"] == "DOCKER")
    accept, nat = docker["rules"]
    assert accept["verdict"] == "accept"
    assert [match["text"] for match in accept["matches"]] == ["iifname docker0", "tcp dport 8080"]
    assert accept["counter"] == {"packets": 3, "bytes": 180}
    assert nat["verdict"] == "nat"
    assert nat["target"] == "DNAT"

    post = result["tables"][1]["chains"][0]
    masquerade = post["rules"][0]
    assert masquerade["verdict"] == "nat"
    assert masquerade["target"] == "MASQUERADE"
    assert "conntrack" in [match["text"] for match in masquerade["matches"]]

    assert result["totals"]["rules"] == 4
    assert result["totals"]["jump"] == 1
    assert result["totals"]["accept"] == 1
    assert result["totals"]["drop"] == 0
    assert result["totals"]["nat"] == 2


def test_nftables_wrapped_payload_is_unwrapped():
    result = normalize_firewall({"backend": "nftables", "rules": {"nftables": NFT_SAMPLE}})

    assert result["available"] is True
    assert [table["name"] for table in result["tables"]] == ["filter", "nat"]
    assert result["totals"]["rules"] == 4


def test_iptables_text_is_normalized():
    result = normalize_firewall({"backend": "iptables", "rules": {"ipv4": IPTABLES_SAMPLE, "ipv6": ""}})

    assert result["available"] is True
    assert [table["name"] for table in result["tables"]] == ["filter", "nat"]

    filter_table = result["tables"][0]
    assert filter_table["family"] == "ip"
    input_chain = next(chain for chain in filter_table["chains"] if chain["name"] == "INPUT")
    assert input_chain["policy"] == "accept"
    assert input_chain["policy_counter"] == {"packets": 10, "bytes": 800}

    docker = next(chain for chain in filter_table["chains"] if chain["name"] == "DOCKER")
    drop, accept = docker["rules"]
    assert drop["verdict"] == "drop"
    assert "! iifname br-0123456789ab" in [match["text"] for match in drop["matches"]]
    assert "oifname br-0123456789ab" in [match["text"] for match in drop["matches"]]
    assert accept["verdict"] == "accept"
    assert accept["comment"] == "web"
    assert "dport 80" in [match["text"] for match in accept["matches"]]

    nat_table = result["tables"][1]
    prerouting = next(chain for chain in nat_table["chains"] if chain["name"] == "PREROUTING")
    assert prerouting["rules"][0]["verdict"] == "jump"
    assert prerouting["rules"][0]["target"] == "DOCKER"
    docker_nat = next(chain for chain in nat_table["chains"] if chain["name"] == "DOCKER")
    ret, dnat = docker_nat["rules"]
    assert ret["verdict"] == "return"
    assert dnat["verdict"] == "nat"
    assert dnat["target"] == "DNAT"
    assert "to-destination 172.20.0.2:80" in [match["text"] for match in dnat["matches"]]


def test_iptables_ipv6_family_is_labelled():
    result = normalize_firewall(
        {"backend": "iptables", "rules": {"ipv4": "", "ipv6": "*filter\n:INPUT ACCEPT [0:0]\nCOMMIT\n"}}
    )

    assert result["tables"][0]["family"] == "ip6"


def test_unknown_backend_yields_empty_view():
    result = normalize_firewall({"backend": "unavailable", "error": "permission denied", "rules": None})

    assert result["available"] is False
    assert result["tables"] == []
    assert result["totals"]["rules"] == 0
    assert "permission denied" in result["warnings"]


def test_missing_payload_is_tolerated():
    result = normalize_firewall(None)

    assert result["backend"] == "unavailable"
    assert result["tables"] == []


def test_table_stats_count_the_rules_of_every_chain():
    result = normalize_firewall({"backend": "nftables", "rules": NFT_SAMPLE})

    assert [table["stats"]["rules"] for table in result["tables"]] == [3, 1]
